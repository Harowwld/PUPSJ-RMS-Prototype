// Generates src/lib/defaultAvatarsGenerated.js: static Boring Avatars SVGs for
// all default avatars (beam variant, 6 seeds x 8 palettes = 48). Run: node scripts/generate-default-avatars.mjs
import React from "react";
import { writeFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import Avatar from "boring-avatars";

const FIRST_ID = 1;

const VARIANT = "beam";

// Different seeds change the face, blob shape and rotation for the same palette.
const SEEDS = ["Ada", "Bryn", "Cato", "Dara", "Eli", "Fenn"];

const PALETTES = [
  { label: "Maroon Gold", colors: ["#800000", "#f5c518", "#fff4d6", "#5a0000", "#e8a317"] },
  { label: "Ocean", colors: ["#0b3d91", "#1e90ff", "#87cefa", "#e0f4ff", "#00bfa6"] },
  { label: "Forest", colors: ["#1b5e20", "#66bb6a", "#c8e6c9", "#f1f8e9", "#a5d6a7"] },
  { label: "Sunset", colors: ["#ff6b35", "#f7c59f", "#efefd0", "#004e89", "#1a659e"] },
  { label: "Orchid", colors: ["#6a4c93", "#c77dff", "#e0aaff", "#240046", "#ff9ecd"] },
  { label: "Candy", colors: ["#ff595e", "#ffca3a", "#8ac926", "#1982c4", "#6a4c93"] },
  { label: "Slate", colors: ["#1f2937", "#4b5563", "#9ca3af", "#e5e7eb", "#f9fafb"] },
  { label: "Coral", colors: ["#ff7f50", "#ffd1dc", "#20b2aa", "#264653", "#e9c46a"] },
];

function uniquifyIds(svg, prefix) {
  const ids = [...svg.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  let out = svg;
  for (const id of new Set(ids)) {
    const safe = `${prefix}-${id.replace(/[^a-zA-Z0-9_-]/g, "")}`;
    out = out.split(`id="${id}"`).join(`id="${safe}"`).split(`url(#${id})`).join(`url(#${safe})`);
  }
  return out;
}

function hexToRgb(hex) {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}`;
}

const entries = [];
let id = FIRST_ID;
for (const seedName of SEEDS) {
  for (const palette of PALETTES) {
    const name = `Avatar ${id}`;
    const seed = `${seedName}-${palette.label}`;
    const markup = renderToStaticMarkup(
      React.createElement(Avatar, { name: seed, variant: VARIANT, colors: palette.colors, size: 40, title: true })
    ).replace(/<title>[^<]*<\/title>/, `<title>${name}</title>`);
    entries.push({
      id,
      name,
      alt: name,
      rgb: hexToRgb(palette.colors[0]),
      svgString: uniquifyIds(markup, `av${id}`),
    });
    id += 1;
  }
}

const body = `// AUTO-GENERATED by scripts/generate-default-avatars.mjs. Do not edit by hand.\nexport const GENERATED_AVATARS = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(new URL("../src/lib/defaultAvatarsGenerated.js", import.meta.url), body);
console.log(`Wrote ${entries.length} avatars (ids ${FIRST_ID}-${id - 1})`);

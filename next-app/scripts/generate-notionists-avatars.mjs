// Generates src/lib/notionistsAvatarsGenerated.js: static DiceBear Notionists SVGs
// Run: node scripts/generate-notionists-avatars.mjs
import { writeFileSync } from "node:fs";
import { Style, Avatar } from "@dicebear/core";
import notionistsDefinition from "@dicebear/styles/notionists.json" with { type: "json" };

const style = new Style(notionistsDefinition);

const FIRST_ID = 1;

export const NOTIONISTS_NAMES = [
  "Orion",
  "Luna",
  "Atlas",
  "Nova",
  "Zephyr",
  "Aria",
  "Cosmo",
  "Maya",
  "Felix",
  "Iris",
  "Apollo",
  "Chloe",
  "Kael",
  "Elena",
  "Milo",
  "Vesper",
  "Silas",
  "Tara",
  "Sora",
];

// High-contrast, bold vibrant pop backdrops that make Notionists line art pop
const PALETTES = [
  "ff5d8f", // Vibrant Hot Pink (User request)
  "06b6d4", // Electric Cyan
  "f97316", // Bright Tangerine
  "10b981", // Emerald
  "8b5cf6", // Royal Violet
  "f59e0b", // Amber Gold
  "3b82f6", // Cobalt Blue
  "ec4899", // Neon Magenta
  "14b8a6", // Bright Teal
  "f43f5e", // Crimson Rose
  "6366f1", // Vivid Indigo
  "84cc16", // Lime Punch
];

function uniquifyIds(svg, prefix) {
  const ids = [...svg.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  if (!ids.length) return svg;
  const uniqueIds = [...new Set(ids)].sort((a, b) => b.length - a.length);

  let out = svg;
  for (const rawId of uniqueIds) {
    const safePrefix = prefix.replace(/[^a-zA-Z0-9_-]/g, "");
    const safeId = `${safePrefix}-${rawId.replace(/[^a-zA-Z0-9_-]/g, "")}`;
    out = out.split(`id="${rawId}"`).join(`id="${safeId}"`);
    out = out.split(`href="#${rawId}"`).join(`href="#${safeId}"`);
    out = out.split(`xlink:href="#${rawId}"`).join(`xlink:href="#${safeId}"`);
    out = out.split(`url(#${rawId})`).join(`url(#${safeId})`);
    out = out.split(`url('#${rawId}')`).join(`url('#${safeId}')`);
    out = out.split(`url("#${rawId}")`).join(`url("#${safeId}")`);
  }
  return out;
}

function cleanSvg(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<metadata[\s\S]*?<\/metadata>/g, "")
    .trim();
}

const entries = [];
let id = FIRST_ID;

for (let i = 0; i < NOTIONISTS_NAMES.length; i++) {
  const name = NOTIONISTS_NAMES[i];
  const bg = PALETTES[i % PALETTES.length];
  const avatar = new Avatar(style, {
    seed: `${name}-pup`,
    borderRadius: 50,
    backgroundColor: [bg],
    title: name,
    gestureProbability: 50,
    glassesProbability: 40,
    beardProbability: 35,
    clothesGraphicProbability: 75,
  });

  const rawSvg = avatar.toString();
  const cleaned = cleanSvg(rawSvg);
  const scopedSvg = uniquifyIds(cleaned, `notionist${id}`);

  entries.push({
    id,
    name,
    alt: `${name} (Notionist)`,
    bgHex: `#${bg}`,
    seed: `${name}-pup`,
    svgString: scopedSvg,
  });

  id += 1;
}

const body = `// AUTO-GENERATED by scripts/generate-notionists-avatars.mjs. Do not edit by hand.\nexport const GENERATED_NOTIONISTS = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(new URL("../src/lib/notionistsAvatarsGenerated.js", import.meta.url), body);
console.log(`Wrote ${entries.length} Notionists avatars (ids ${FIRST_ID}-${id - 1}) to src/lib/notionistsAvatarsGenerated.js`);

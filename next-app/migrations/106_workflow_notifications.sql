ALTER TABLE document_requests
  ADD COLUMN IF NOT EXISTS portal_submitter_account_id bigint REFERENCES student_accounts(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS pickup_instructions text;

CREATE TABLE IF NOT EXISTS workflow_notification_preferences (
  principal_type text NOT NULL CHECK (principal_type IN ('portal', 'staff')),
  principal_id text NOT NULL,
  event_key text NOT NULL,
  channel text NOT NULL CHECK (channel IN ('in_app', 'email')),
  enabled boolean NOT NULL,
  PRIMARY KEY (principal_type, principal_id, event_key, channel)
);

CREATE TABLE IF NOT EXISTS portal_workflow_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES student_accounts(id) ON DELETE CASCADE,
  event_key text NOT NULL,
  target_path text NOT NULL,
  in_app boolean NOT NULL,
  read_at timestamptz,
  email_state text NOT NULL CHECK (email_state IN ('none', 'pending', 'sent', 'failed', 'skipped')),
  email_attempts integer NOT NULL DEFAULT 0,
  next_email_attempt_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS portal_workflow_notifications_inbox
  ON portal_workflow_notifications (account_id, id DESC) WHERE in_app;

CREATE INDEX IF NOT EXISTS portal_workflow_notifications_outbox
  ON portal_workflow_notifications (next_email_attempt_at, id) WHERE email_state = 'pending';


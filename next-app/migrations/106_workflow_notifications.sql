-- Old online requests recorded a portal actor and a specific submission message.
-- Link only requests for which both pieces of evidence agree with the existing profile.
UPDATE document_requests request
   SET portal_submitter_account_id = account.id
  FROM student_accounts account
 WHERE request.portal_submitter_account_id IS NULL
   AND request.office_id = 'registrar'
   AND account.identity_profile_id = request.identity_profile_id
   AND EXISTS (
     SELECT 1
       FROM transaction_updates initial
      WHERE initial.id = (
        SELECT id FROM transaction_updates
         WHERE document_request_id = request.id ORDER BY id LIMIT 1
      )
        AND initial.status = 'Pending'
        AND initial.created_by IN (account.id::text, account.student_no)
        AND (initial.message = 'Request submitted.'
          OR initial.message ~ '^Request submitted with [0-9]+ supporting attachment\(s\)( including Special Power of Attorney \(SPA\))?\.$')
   );


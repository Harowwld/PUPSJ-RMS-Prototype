CREATE OR REPLACE FUNCTION normalize_legacy_icon_json(input_json JSONB)
RETURNS JSONB LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  result JSONB;
BEGIN
  CASE jsonb_typeof(input_json)
    WHEN 'string' THEN RETURN to_jsonb(normalize_legacy_icon_text(input_json #>> '{}'));
    WHEN 'array' THEN
      SELECT COALESCE(jsonb_agg(normalize_legacy_icon_json(value)), '[]'::jsonb)
        INTO result FROM jsonb_array_elements(input_json) AS items(value);
      RETURN result;
    WHEN 'object' THEN
      SELECT COALESCE(jsonb_object_agg(key, normalize_legacy_icon_json(value)), '{}'::jsonb)
        INTO result FROM jsonb_each(input_json) AS items(key, value);
      RETURN result;
    ELSE RETURN input_json;
  END CASE;
END;
$$;

UPDATE modules SET icon = normalize_legacy_icon_text(icon) WHERE icon ~ '(ph-|ti-)';
UPDATE offices SET icon = normalize_legacy_icon_text(icon) WHERE icon ~ '(ph-|ti-)';
UPDATE office_modules SET config = normalize_legacy_icon_json(config) WHERE config IS NOT NULL AND config::text ~ '(ph-|ti-)';
UPDATE settings SET value = normalize_legacy_icon_json(value::jsonb)::text
  WHERE value ~ '^\s*[\[{"].*(ph-|ti-).*';

DROP FUNCTION normalize_legacy_icon_json(JSONB);
DROP FUNCTION normalize_legacy_icon_text(TEXT);
